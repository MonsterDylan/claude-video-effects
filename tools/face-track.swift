// face-track.swift: per-frame face boxes for FX.faceCallout (and anything else that wants to follow the head).
// Uses Apple's Vision framework (built into macOS, nothing to install).
// Usage: swift face-track.swift <video> <out.js> [fps=10] [compW=1080] [compH=1920]
// Output: window.FX_FACE = { fps, frames: [[t, cx, cy, w, h], ...] } in COMPOSITION pixels,
// assuming the plate is drawn object-fit: cover, centered (the fx-scene default).
import Foundation
import AVFoundation
import Vision
import CoreGraphics

let a = CommandLine.arguments
guard a.count >= 3 else { print("usage: swift face-track.swift <video> <out.js> [fps] [compW] [compH]"); exit(1) }
let url = URL(fileURLWithPath: a[1]), out = a[2]
let fps = a.count > 3 ? Double(a[3])! : 10
let compW = a.count > 4 ? Double(a[4])! : 1080, compH = a.count > 5 ? Double(a[5])! : 1920

let asset = AVURLAsset(url: url)
let dur = CMTimeGetSeconds(asset.duration)
let gen = AVAssetImageGenerator(asset: asset)
gen.appliesPreferredTrackTransform = true
gen.requestedTimeToleranceBefore = .zero
gen.requestedTimeToleranceAfter = .zero
gen.maximumSize = CGSize(width: 720, height: 720)

var frames: [[Double]] = []
var last: [Double]? = nil
var t = 0.0, misses = 0
while t <= dur {
  let time = CMTime(seconds: t, preferredTimescale: 600)
  if let img = try? gen.copyCGImage(at: time, actualTime: nil) {
    let sw = Double(img.width), sh = Double(img.height)
    let req = VNDetectFaceRectanglesRequest()
    try? VNImageRequestHandler(cgImage: img, options: [:]).perform([req])
    let faces = (req.results ?? []).sorted { $0.boundingBox.width * $0.boundingBox.height > $1.boundingBox.width * $1.boundingBox.height }
    if let f = faces.first {
      let bb = f.boundingBox
      // Vision: normalized, origin bottom-left -> source px, origin top-left
      let sx = bb.midX * sw, sy = (1 - bb.midY) * sh, bw = bb.width * sw, bh = bb.height * sh
      // object-fit: cover, centered
      let s = max(compW / sw, compH / sh), ox = (compW - sw * s) / 2, oy = (compH - sh * s) / 2
      let row = [(t * 1000).rounded() / 1000, (sx * s + ox).rounded(), (sy * s + oy).rounded(), (bw * s).rounded(), (bh * s).rounded()]
      frames.append(row); last = row
    } else if var l = last { l[0] = (t * 1000).rounded() / 1000; frames.append(l); misses += 1 } else { misses += 1 }
  }
  t += 1.0 / fps
}
let rows = frames.map { "[\($0.map { String(format: "%g", $0) }.joined(separator: ","))]" }.joined(separator: ",")
let js = "// generated by tools/face-track.swift from \(url.lastPathComponent)\nwindow.FX_FACE = { fps: \(fps), frames: [\(rows)] };\n"
try! js.write(toFile: out, atomically: true, encoding: .utf8)
print("face-track: \(frames.count) frames, \(misses) misses -> \(out)")
